import { test, expect } from '@playwright/test';

// Recorrido CU-09 con API, sesiones JDBC, MySQL y Mailpit reales.
test('consulta, valida, edita, verifica correo y desactiva conservando el perfil', async ({ page, request }) => {
  test.setTimeout(90_000);
  await page.goto('/');
  await page.getByRole('button', { name: 'Ver cuenta', exact: true }).click();
  await page.locator('ion-input[name="correo"] input').fill('cu09-real@example.test');
  await page.locator('ion-input[name="clave"] input').fill('Cu08RealTestPassword!');
  await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
  await expect(page.locator('.welcome-strip')).toContainText('cu09-real');
  await page.getByRole('button',{name:'Cerrar panel',exact:true}).click();
  await page.getByRole('button', { name: 'Mi perfil y preferencias', exact: true }).click();
  const profile=page.locator('app-perfil-personal');
  await expect(profile).toContainText('Ana Perfil');
  await profile.getByRole('button', {name:'Editar perfil y preferencias',exact:true}).click();
  await profile.locator('ion-input[name="fullName"] input').fill('Ana Actualizada');
  await profile.locator('ion-input[name="birthDate"] input').fill('2999-01-01');
  await profile.getByRole('button',{name:'Revisar cambios',exact:true}).click();
  await expect(profile).toContainText('La fecha no puede ser futura');
  await expect(profile.locator('ion-input[name="fullName"] input')).toHaveValue('Ana Actualizada');
  await profile.locator('ion-input[name="birthDate"] input').fill('1999-01-01');
  await profile.locator('ion-input[name="email"] input').fill('cu09-nuevo@example.test');
  await profile.locator('ion-checkbox[name="promotions"]').click();
  await profile.getByRole('button',{name:'Revisar cambios',exact:true}).click();
  await profile.locator('ion-input[name="currentPassword"] input').fill('incorrecta');
  await profile.getByRole('button',{name:'Confirmar y guardar',exact:true}).click();
  await expect(profile).toContainText('La contraseña actual es incorrecta');
  await profile.locator('ion-input[name="currentPassword"] input').fill('Cu08RealTestPassword!');
  await profile.getByRole('button',{name:'Confirmar y guardar',exact:true}).click();
  await expect(profile).toContainText('Verificar nuevo correo');
  expect((await (await page.request.get('/api/account/profile')).json()).email).toBe('cu09-real@example.test');
  await profile.locator('ion-input[name="claveCorreo"] input').fill('Cu08RealTestPassword!');
  await profile.getByRole('button',{name:'Reenviar cambio de correo',exact:true}).click();
  await expect(profile).toContainText('Se envió un nuevo código');
  expect((await (await page.request.get('/api/account/profile')).json()).promotions).toBe(true);
  const mailUrl=process.env['CU09_MAIL_URL']!;
  let token='';
  await expect.poll(async()=>{
    const list=await (await request.get(`${mailUrl}/api/v1/messages`)).json();
    if(list.messages?.length!==2)return false;
    const message=await (await request.get(`${mailUrl}/api/v1/message/${list.messages[0].ID}`)).json();
    token=message.Text.match(/(?:^|\s)([A-Za-z0-9_-]{43})(?=\s|$)/)?.[1]??'';
    return !!token;
  }).toBe(true);
  await profile.locator('ion-input[name="codigoCorreo"] input').fill(token);
  await profile.getByRole('button',{name:'Confirmar nuevo correo',exact:true}).click();
  await expect(page.getByRole('dialog',{name:'Acceso a tu cuenta',exact:true})).toBeVisible();
  await page.locator('ion-input[name="correo"] input').fill('cu09-nuevo@example.test');
  await page.locator('ion-input[name="clave"] input').fill('Cu08RealTestPassword!');
  await page.getByRole('button',{name:'Iniciar sesión',exact:true}).click();
  await expect(page.locator('.welcome-strip')).toContainText('cu09-nuevo');
  await page.getByRole('button',{name:'Cerrar panel',exact:true}).click();
  await page.getByRole('button',{name:'Mi perfil y preferencias',exact:true}).click();
  await expect(profile).toContainText('Ana Actualizada');
  await profile.getByRole('button',{name:'Solicitar cierre de cuenta',exact:true}).click();
  await expect(profile).toContainText('Se conservarán pedidos');
  await profile.locator('ion-input[name="claveCierre"] input').fill('Cu08RealTestPassword!');
  await profile.locator('ion-checkbox[name="confirmClosure"]').click();
  await profile.getByRole('button',{name:'Desactivar mi cuenta',exact:true}).click();
  await expect(page.locator('.welcome-strip')).toContainText('visitante');
  expect((await page.request.get('/api/account/profile')).status()).toBe(401);
});
